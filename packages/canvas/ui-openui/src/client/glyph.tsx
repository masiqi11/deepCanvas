/**
 * Normalize an icon name: "MapPin", "map_pin" and "map pin" all mean "map-pin".
 * @param value - model-written icon name.
 * @returns the icon component, or undefined for an unknown name.
 */
export function iconFor(value: unknown): LucideIcon | undefined {
  if (typeof value !== 'string') return undefined
  const name = value.trim().replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/[\s_]+/g, '-').toLowerCase()
  return ICONS.get(name)
}

/**
 * Draw a lucide icon by name.
 * @param props - icon name, pixel size, and optional class.
 * @returns the icon, or null for an unknown name.
 */
export function Glyph({ name, size = 18, className }: { name: unknown; size?: number; className?: string | undefined }) {
  const Icon = iconFor(name)
  if (Icon === undefined) return null
  return <Icon size={size} strokeWidth={1.8} aria-hidden className={className} />
}
